'''Audit and document the cross-validation/tuning protocol used by the benchmark.

This audit uses the same source generator and model factory as the verified
benchmark. It does not retrain the six expensive full models; it verifies the
shared data construction, class counts, split, CV, parameter grids, imbalance
handling, and ARL0 calibration contract, then writes an auditable manifest.
'''
from __future__ import annotations
import json, platform, sys
from pathlib import Path
import numpy as np
import pandas as pd
from sklearn.model_selection import StratifiedKFold, train_test_split
HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[2]
SOURCE=ROOT/"reviewer1_ml_benchmark"
OUT=HERE/"outputs"
sys.path.insert(0,str(ROOT))
sys.path.insert(0,str(SOURCE))
import ml_reviewer_benchmark as core
from run_one_model import MODELS, build_model

def serial(obj):
    if isinstance(obj, (np.integer,)): return int(obj)
    if isinstance(obj, (np.floating,)): return float(obj)
    if isinstance(obj, np.ndarray): return obj.tolist()
    return str(obj)


def main():
    seed=20260825; samples_per_class=2000; shifted_fraction=.5
    X,y=core.make_dataset(seed,samples_per_class,1.0,shifted_fraction)
    Xtr,Xte,ytr,yte=train_test_split(X,y,test_size=.2,stratify=y,random_state=seed)
    cv=StratifiedKFold(n_splits=5,shuffle=True,random_state=seed)
    grid_rows=[]; model_rows=[]
    for name in MODELS:
        estimator,grid=build_model(name,seed)
        params={k:[serial(vv) for vv in vals] for k,vals in grid.items()}
        balance=[]
        for step in estimator.steps if hasattr(estimator,'steps') else []:
            if hasattr(step[1],'class_weight'):
                balance.append({'component':step[0],'class_weight':step[1].class_weight})
        if not balance: balance=[{'component':'model','class_weight':'not applicable; balanced class construction'}]
        grid_rows.append({'model':name,'n_grid_combinations':int(np.prod([len(v) for v in grid.values()])),'parameter_grid':json.dumps(params,default=serial),'imbalance_handling':json.dumps(balance,default=serial)})
        model_rows.append({'model':name,'estimator':estimator.__class__.__name__,'pipeline_steps':str(getattr(estimator,'steps',None)),'uses_same_feature_count':X.shape[1]==16,'train_n':len(ytr),'test_n':len(yte),'train_ic':int((ytr==0).sum()),'train_shifted':int((ytr==1).sum()),'test_ic':int((yte==0).sum()),'test_shifted':int((yte==1).sum()),'cv_folds':cv.n_splits,'cv_shuffle':cv.shuffle,'cv_random_state':cv.random_state})
    OUT.mkdir(parents=True,exist_ok=True)
    pd.DataFrame(grid_rows).to_csv(OUT/'hyperparameter_grids_and_imbalance.csv',index=False)
    pd.DataFrame(model_rows).to_csv(OUT/'model_split_and_cv_manifest.csv',index=False)
    manifest={'data_source':'ml_reviewer_benchmark.make_dataset; simulated Phase-I labelled profiles only','seed':seed,'skewness':1.0,'samples_per_class':samples_per_class,'shifted_fraction':shifted_fraction,'total_profiles':len(y),'class_counts':{'in_control':int((y==0).sum()),'shifted':int((y==1).sum())},'split':'train_test_split(test_size=0.20, stratify=y, random_state=20260825)','train_counts':{'in_control':int((ytr==0).sum()),'shifted':int((ytr==1).sum())},'test_counts':{'in_control':int((yte==0).sum()),'shifted':int((yte==1).sum())},'cv':'StratifiedKFold(n_splits=5, shuffle=True, random_state=20260825)','selection_metric':'ROC-AUC','target_arl0':200.0,'calibration_profiles':10000,'calibration_rule':'threshold = empirical quantile of IC scores at 1 - 1/ARL0','imbalance_policy':'shifted_fraction=0.5 creates balanced classes; RF, SVM and Elastic-Net additionally use class_weight=balanced; GB, kNN and MLP use the balanced training data without class weights; stratification is used in both split and CV.','models':MODELS,'source_files':[str(SOURCE/'run_one_model.py'),str(SOURCE/'ml_reviewer_benchmark.py')]}
    (OUT/'cv_tuning_protocol_manifest.json').write_text(json.dumps(manifest,indent=2,default=serial),encoding='utf-8')
    report=f'''# Cross-validation, tuning, and class-balance audit
## Data source
The models are trained only on simulated labelled Phase-I-style profiles generated by `ml_reviewer_benchmark.make_dataset`. The observed transformer data are not used as ML labels or for model fitting. With `shifted_fraction = 0.5`, the dataset contains {len(y)} profiles: {(y==0).sum()} in-control and {(y==1).sum()} shifted.

## Split and validation
A single stratified 80/20 train/test split is shared by all six models. The training data contain {len(ytr)} profiles ({(ytr==0).sum()} IC and {(ytr==1).sum()} shifted); the test data contain {len(yte)} profiles ({(yte==0).sum()} IC and {(yte==1).sum()} shifted). Hyperparameters are selected only within the training set using `StratifiedKFold(n_splits=5, shuffle=True, random_state=20260825)` and ROC-AUC as the selection metric. The test set is used once for final reporting.

## Tuning
The exact parameter grids and number of combinations for each model are in `hyperparameter_grids_and_imbalance.csv`. Every model receives the same 16-feature contract and the same CV folds.

## Class imbalance
The primary design uses equal IC and shifted class counts, so there is no artificial class imbalance in training or testing. Stratification preserves this ratio in every split and fold. Random Forest, SVM, and Elastic-Net logistic regression additionally use `class_weight='balanced'`; this is harmless under equal counts and protects the protocol if the class ratio is changed. Gradient Boosting, kNN, and MLP do not expose class weights in the selected implementation and therefore rely on the balanced training design.

## ARL0 calibration
After model selection, each fitted model is calibrated independently on 10,000 newly generated in-control profiles. Its threshold is the empirical score quantile at `1 - 1/200`, targeting ARL0 = 200. Thus the model comparison is not confounded by different in-control alarm rates. The complete calibrated results are in `../verified_full_results/`.

## Reproducibility
The manifest records the seed, class counts, split, CV design, estimator grids, and imbalance policy. No source benchmark file was modified.
'''
    (OUT/'cross_validation_tuning_report.md').write_text(report,encoding='utf-8')
    print('Audit complete ->',OUT)
if __name__=='__main__': main()
