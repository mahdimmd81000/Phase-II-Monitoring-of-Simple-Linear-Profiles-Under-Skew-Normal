def make_shared_data(seed, samples_per_class, skewness, shifted_fraction):
    """One shared simulated Phase I dataset for ALL models (no per-model data)."""
    x, y = core.make_dataset(seed, samples_per_class, skewness, shifted_fraction)
    x_train, x_test, y_train, y_test = train_test_split(
        x, y, test_size=.2, stratify=y, random_state=seed)
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=seed)
    return x, y, x_train, x_test, y_train, y_test, cv


def fold_class_balance(cv, y_train):
    """Record in-control/shifted counts inside every CV fold (imbalance audit)."""
    rows = []
    for fold, (tr, te) in enumerate(cv.split(np.zeros(len(y_train)), y_train), 1):
        rows.append({
            "fold": fold,
            "train_ic": int((y_train[tr] == 0).sum()),
            "train_shifted": int((y_train[tr] == 1).sum()),
            "val_ic": int((y_train[te] == 0).sum()),
            "val_shifted": int((y_train[te] == 1).sum()),
        })
    return pd.DataFrame(rows)


def tune_and_evaluate(name, shared, seed):
    """Grid search + 5-fold stratified CV + holdout evaluation for one model."""
    x_train, x_test, y_train, y_test, cv = shared[2], shared[3], shared[4], shared[5], shared[6]
    estimator, grid = build_model(name, seed)
    started = time.perf_counter()
    search = GridSearchCV(estimator, grid, scoring="roc_auc", cv=cv, n_jobs=-1,
                          return_train_score=False)
    search.fit(x_train, y_train)
    elapsed = time.perf_counter() - started

    model = search.best_estimator_
    probability = search.predict_proba(x_test)[:, 1]
    prediction = (probability >= .5).astype(int)
    tn, fp, fn, tp = ((prediction == 0) & (y_test == 0)).sum(), \
                     ((prediction == 1) & (y_test == 0)).sum(), \
                     ((prediction == 0) & (y_test == 1)).sum(), \
                     ((prediction == 1) & (y_test == 1)).sum()

    # complete tuning record: every parameter combination x every fold
    cvres = pd.DataFrame(search.cv_results_)
    fold_cols = [c for c in cvres.columns if c.startswith("split") and c.endswith("_test_score")]
    tuning = pd.DataFrame({
        "model": name,
        "params": [str(p) for p in cvres["params"]],
        "mean_cv_auc": cvres["mean_test_score"],
        "std_cv_auc": cvres["std_test_score"],
        "rank": cvres["rank_test_score"],
        **{f"fold{k}_auc": cvres[c].to_numpy() for k, c in enumerate(fold_cols, 1)},
    })
    metrics = {
        "model": name,
        "selected_params": search.best_params_,
        "n_param_combinations": len(cvres),
        "cv_auc_mean": float(search.best_score_),
        "cv_auc_std": float(cvres.loc[cvres["rank_test_score"] == 1, "std_test_score"].iloc[0]),
        "test_auc": float(__import__("sklearn.metrics", fromlist=["roc_auc_score"])
                          .roc_auc_score(y_test, probability)),
        "detection_rate_recall": float(tp) / max(tp + fn, 1),
        "false_alarm_rate": float(fp) / max(fp + tn, 1),
        "mcc": float(__import__("sklearn.metrics", fromlist=["matthews_corrcoef"])
                     .matthews_corrcoef(y_test, prediction)),
        "tuning_seconds": elapsed,
    }
    return model, metrics, tuning


def calibrate_with_provenance(model, seed, skewness, calibration_profiles):
    """ARL0 threshold from a SEPARATE simulated in-control stream (seed+7000)."""
    threshold, alarm_rate, n = core.calibrate_model_threshold(
        model, seed + 7000, skewness, calibration_profiles=calibration_profiles)
    return {"threshold": threshold, "calibration_profiles": n,
            "calibration_seed": seed + 7000, "training_seed": seed,
            "streams_disjoint": (seed + 7000) != seed,
            "empirical_arl0": 1.0 / max(alarm_rate, 1e-12),
            "target_arl0": core.TARGET_ARL0}


def run_prevalence(seed, samples_per_class, skewness, shifted_fraction,
                   calibration_profiles, arl_replications, arl_horizon, tag):
    """Run the full documented protocol at one class prevalence."""
    shared = make_shared_data(seed, samples_per_class, skewness, shifted_fraction)
    x, y, x_train, x_test, y_train, y_test, cv = shared
    fold_balance = fold_class_balance(cv, y_train)

    class_balance = {
        "shifted_fraction_requested": shifted_fraction,
        "prevalence_in_dataset": float(np.mean(y == 1)),
        "n_total": int(len(y)),
        "train_ic": int((y_train == 0).sum()),
        "train_shifted": int((y_train == 1).sum()),
        "test_ic": int((y_test == 0).sum()),
        "test_shifted": int((y_test == 1).sum()),
        "imbalance_handling": {
            "class_weight_balanced": ["RandomForest", "SVM", "ElasticNetLogistic"],
            "not_supported_but_balanced_by_design": ["GradientBoosting", "kNN", "MLP"],
            "note": "prevalence is set explicitly by shifted_fraction; estimators "
                    "supporting class_weight use 'balanced'; fold composition is "
                    "recorded in outputs/fold_class_balance.csv",
        },
    }

    comparison_rows, calibration_rows = [], []
    for name in MODELS:
        model, metrics, tuning = tune_and_evaluate(name, shared, seed)
        tuning.to_csv(OUT / f"cv_results_{tag}_{name}.csv", index=False)
        cal = calibrate_with_provenance(model, seed, skewness, calibration_profiles)
        metrics["empirical_arl0"] = cal["empirical_arl0"]
        comparison_rows.append(metrics)
        calibration_rows.append({"model": name, **cal})
        print(f"  [{tag}] {name}: cv_auc={metrics['cv_auc_mean']:.3f} "
              f"test_auc={metrics['test_auc']:.3f} ARL0={cal['empirical_arl0']:.0f}",
              flush=True)

    comparison = pd.DataFrame(comparison_rows)
    comparison["prevalence"] = shifted_fraction
    comparison.to_csv(OUT / f"model_comparison_{tag}.csv", index=False)
    pd.DataFrame(calibration_rows).to_csv(OUT / f"calibration_{tag}.csv", index=False)
    fold_balance.to_csv(OUT / f"fold_class_balance_{tag}.csv", index=False)
    (OUT / f"class_balance_{tag}.json").write_text(
        json.dumps(class_balance, indent=2), encoding="utf-8")
    return comparison


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed", type=int, default=core.SEED)
    parser.add_argument("--samples-per-class", type=int, default=2000)
    parser.add_argument("--skewness", type=float, default=1.0)
    parser.add_argument("--shifted-fraction", type=float, default=0.5)
    parser.add_argument("--calibration-profiles", type=int, default=core.CALIBRATION_PROFILES)
    parser.add_argument("--prevalence-sweep", action="store_true",
                        help="repeat the protocol at a second, stronger imbalance")
    parser.add_argument("--quick", action="store_true")
    args = parser.parse_args()

    if args.quick:
        args.samples_per_class, args.calibration_profiles = 400, 2000

    OUT.mkdir(exist_ok=True)
    LOGS.mkdir(exist_ok=True)

    prevalences = [args.shifted_fraction]
    if args.prevalence_sweep:
        prevalences = sorted({0.1, args.shifted_fraction})

    all_prevalences = []
    for i, prev in enumerate(prevalences):
        print(f"=== prevalence (shifted fraction) = {prev} ===", flush=True)
        comparison = run_prevalence(args.seed, args.samples_per_class, args.skewness,
                                    prev, args.calibration_profiles,
                                    core.ARL_REPLICATIONS if not args.quick else 200,
                                    core.ARL_HORIZON if not args.quick else 100,
                                    tag=f"p{str(prev).replace('.', '')}")
        all_prevalences.append(comparison)

    pd.concat(all_prevalences, ignore_index=True).to_csv(
        OUT / "model_comparison.csv", index=False)

    provenance = {
        "training_source": "simulated Phase I profiles only "
                           "(ml_reviewer_benchmark.make_dataset: in-control + shifted "
                           "profiles generated by the Phase I simulator); no real or "
                           "Phase II data is used for training, tuning or calibration",
        "seeds": {
            "dataset_and_split": args.seed,
            "cross_validation_folds": args.seed,
            "arl0_calibration_stream": args.seed + 7000,
            "arl_estimation_streams": [args.seed + 9000 + i for i in range(3)],
        },
        "split": "stratified 80/20 holdout, random_state=20260825",
        "cv": "StratifiedKFold(n_splits=5, shuffle=True, random_state=20260825), "
              "identical folds for all six models",
        "tuning": "GridSearchCV(scoring='roc_auc'); complete per-combination, "
                  "per-fold results in outputs/cv_results_*.csv",
        "class_imbalance": "prevalence fixed by shifted_fraction and recorded; "
                           "class_weight='balanced' where supported; per-fold class "
                           "counts in outputs/fold_class_balance_*.csv",
        "software": {"python": platform.python_version(),
                     "scikit-learn": sklearn.__version__,
                     "numpy": np.__version__},
        "quick_mode": args.quick,
    }
    (OUT / "provenance.json").write_text(json.dumps(provenance, indent=2),
                                         encoding="utf-8")
    print("Done. Outputs in", OUT)


if __name__ == "__main__":
    main()


